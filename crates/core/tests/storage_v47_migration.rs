// Issue #930 (FR-006 / FR-007 / FR-008): a database created by lcg on lbug 0.21.2 (storage
// version 47) must open under the current lbug-0.23.0-pinned binary (storage version 53),
// lose nothing, and serve correct reads, non-ASCII FTS and HNSW vector searches. Because the
// lbug version differs from the one that built the FTS indexes, the ADR-0649 rebuild-on-version-
// change path must fire too.
//
// The fixture (crates/core/tests/fixtures/storage_v47_db/t.db.tar.gz) was written by the
// unchanged 0.21.2 binary before any pin moved; see its README.md for contents and build steps.
// It can only be regenerated by a 0.21.2-linked build. Structurally modelled on
// storage_v42_migration.rs and fts_lbug020_migration.rs.

use std::path::{Path, PathBuf};

use lcg_core::db::{Conn, Db};
use tempfile::TempDir;

/// The fixture's embedding dimension (see its README).
const DIM: usize = 768;
/// The lbug version that built the fixture and its FTS indexes.
const FIXTURE_LBUG_VERSION: &str = "0.21.2";
const MARKER_QUERY: &str = "MATCH (s:SchemaState {key: 'fts_built_by_lbug'}) RETURN s.status";

fn extract_fixture() -> (TempDir, PathBuf) {
    let dir = TempDir::new().unwrap();
    let archive =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/storage_v47_db/t.db.tar.gz");
    assert!(
        archive.exists(),
        "storage-v47 fixture not found at {}",
        archive.display()
    );
    let status = std::process::Command::new("tar")
        .arg("-xzf")
        .arg(&archive)
        .arg("-C")
        .arg(dir.path())
        .status()
        .expect("failed to invoke tar");
    assert!(status.success(), "tar extraction of the fixture failed");
    let db_path = dir.path().join("t.db");
    assert!(db_path.exists(), "t.db missing after extraction");
    (dir, db_path)
}

fn rows(conn: &Conn<'_>, cypher: &str) -> Vec<Vec<String>> {
    conn.cypher_query(cypher)
        .unwrap_or_else(|e| panic!("{cypher}: {e}"))
}

fn fts(conn: &Conn<'_>, table: &str, index: &str, term: &str) -> Vec<Vec<String>> {
    rows(
        conn,
        &format!("CALL QUERY_FTS_INDEX('{table}', '{index}', '{term}') RETURN node.uuid"),
    )
}

fn marker(conn: &Conn<'_>) -> Option<String> {
    rows(conn, MARKER_QUERY)
        .into_iter()
        .next()
        .map(|r| r[0].clone())
}

fn one_uuid(conn: &Conn<'_>, cypher: &str) -> String {
    rows(conn, cypher)
        .into_iter()
        .next()
        .unwrap_or_else(|| panic!("no row for {cypher}"))[0]
        .clone()
}

/// Reads a `FLOAT[]` column from the first row of `cypher` as `Vec<f32>`.
fn embedding(conn: &Conn<'_>, cypher: &str) -> Vec<f32> {
    let row = conn
        .query_cypher_raw(cypher)
        .unwrap()
        .next()
        .unwrap_or_else(|| panic!("no row for {cypher}"));
    match &row[0] {
        lbug::Value::List(_, xs) | lbug::Value::Array(_, xs) => xs
            .iter()
            .map(|v| match v {
                lbug::Value::Float(f) => *f,
                lbug::Value::Double(d) => *d as f32,
                other => panic!("unexpected embedding element {other:?}"),
            })
            .collect(),
        other => panic!("expected an embedding list, got {other:?}"),
    }
}

/// Every read the fixture must still serve after migration (and again after a checkpoint).
fn assert_reads_correct(conn: &Conn<'_>) {
    // Zero loss (SC-004).
    assert_eq!(conn.count_nodes("Entity").unwrap(), 4);
    assert_eq!(conn.count_nodes("Episodic").unwrap(), 2);
    assert_eq!(conn.count_relates_to_edges().unwrap(), 2);

    // Content survived, including non-ASCII values.
    let summary = one_uuid(
        conn,
        "MATCH (e:Entity) WHERE e.name = 'Alice' RETURN e.summary",
    );
    assert_eq!(summary, "Alice lives in Zürich");
    assert_eq!(
        one_uuid(
            conn,
            "MATCH (e:Entity) WHERE e.name = '東京' RETURN e.summary"
        ),
        "Capital of Japan"
    );
    assert_eq!(
        one_uuid(
            conn,
            "MATCH (r:RelatesToNode_) WHERE r.name = 'LIVES_IN' RETURN r.fact"
        ),
        "Alice → Zürich"
    );
    assert_eq!(
        one_uuid(
            conn,
            "MATCH (e:Episodic {uuid: 'ep-nonascii'}) RETURN e.content"
        ),
        "Alice — moved to Zürich, then visited 東京"
    );

    // FTS with non-ASCII terms (the ADR-0649 failure class).
    assert_eq!(
        fts(conn, "Entity", "node_name_and_summary", "Zürich").len(),
        2
    );
    assert_eq!(
        fts(conn, "Entity", "node_name_and_summary", "東京").len(),
        1
    );
    assert_eq!(
        fts(conn, "RelatesToNode_", "edge_name_and_fact", "→").len(),
        1
    );
    assert_eq!(fts(conn, "Episodic", "episode_content", "—").len(), 1);

    // HNSW vector search (index survived the 47 -> 53 jump): querying with a stored embedding
    // must return that very row first, at ~zero distance.
    let zurich_uuid = one_uuid(
        conn,
        "MATCH (e:Entity) WHERE e.name = 'Zürich' RETURN e.uuid",
    );
    let q = embedding(
        conn,
        "MATCH (e:Entity) WHERE e.name = 'Zürich' RETURN e.name_embedding",
    );
    assert_eq!(q.len(), DIM, "fixture embedding dimension changed");
    let hits = conn.vector_search_entities(&q, None, 4).unwrap();
    assert_eq!(hits.len(), 4, "HNSW search should see all 4 entities");
    assert_eq!(hits[0].0, zurich_uuid, "nearest to Zürich must be Zürich");
    assert!(hits[0].1.abs() < 1e-4, "self-distance {}", hits[0].1);

    let edge_uuid = one_uuid(
        conn,
        "MATCH (r:RelatesToNode_) WHERE r.name = 'KNOWS' RETURN r.uuid",
    );
    let eq = embedding(
        conn,
        "MATCH (r:RelatesToNode_) WHERE r.name = 'KNOWS' RETURN r.fact_embedding",
    );
    let ehits = conn.vector_search_edges(&eq, None, 2).unwrap();
    assert_eq!(ehits.len(), 2);
    assert_eq!(ehits[0].0, edge_uuid);
    assert!(ehits[0].1.abs() < 1e-4);
}

/// FR-006 / FR-007 / SC-004: open is automatic, nothing is lost, FTS + vector search work, and
/// everything still holds after a clean close (which checkpoints into storage 53) and reopen.
#[test]
fn storage_v47_database_opens_migrates_and_serves_reads_and_searches() {
    let (_dir, db_path) = extract_fixture();
    {
        let db = Db::open(db_path.to_str().unwrap()).expect(
            "storage-v47 database failed to open under the current lbug pin; opening it is \
             expected to be automatic",
        );
        let conn = db.connect().unwrap();
        conn.init_schema(DIM).unwrap(); // the real open path
        assert_reads_correct(&conn);
    }
    // Dropping the Db closes it cleanly (checkpoint); the reopened file is now storage 53.
    let db = Db::open(db_path.to_str().unwrap()).expect("reopen after checkpoint failed");
    let conn = db.connect().unwrap();
    conn.init_schema(DIM).unwrap();
    assert_reads_correct(&conn);
}

/// FR-008 / ADR-0649: the 0.21.2 -> 0.23.0 version change triggers the FTS rebuild. The marker
/// reads the fixture's builder version before the real open path and `lbug::VERSION` after; the
/// rebuild is not recorded to the WAL (ADR-0015); non-ASCII rows are writable afterwards and the
/// statement-level backstop never has to fire.
#[test]
fn fts_rebuild_fires_on_lbug_version_change() {
    assert_ne!(
        lbug::VERSION,
        FIXTURE_LBUG_VERSION,
        "the fixture must come from a different lbug version than the current pin"
    );
    let (_dir, db_path) = extract_fixture();
    let db = Db::open(db_path.to_str().unwrap()).unwrap();
    let conn = db.connect().unwrap();
    assert_eq!(
        marker(&conn).as_deref(),
        Some(FIXTURE_LBUG_VERSION),
        "fixture marker should name the 0.21.2 builder"
    );
    let _ = conn.drain_mutations();

    conn.init_schema(DIM).unwrap();
    assert_eq!(marker(&conn).as_deref(), Some(lbug::VERSION));
    assert!(
        conn.drain_mutations().is_empty(),
        "the FTS rebuild must not be recorded to the WAL (ADR-0015)"
    );

    // Writes through the (rebuilt) indexes on non-ASCII rows succeed without a backstop repair.
    let edge = one_uuid(
        &conn,
        "MATCH (r:RelatesToNode_) WHERE r.fact CONTAINS '→' RETURN r.uuid",
    );
    conn.run_cypher(&format!(
        "MATCH (r:RelatesToNode_ {{uuid: '{edge}'}}) DETACH DELETE r"
    ))
    .unwrap();
    assert!(fts(&conn, "RelatesToNode_", "edge_name_and_fact", "→").is_empty());
    conn.run_cypher("MATCH (e:Episodic {uuid: 'ep-nonascii'}) DETACH DELETE e")
        .unwrap();
    assert!(fts(&conn, "Episodic", "episode_content", "—").is_empty());
    conn.run_cypher(
        "MATCH (e:Entity) WHERE e.name = '東京' SET e.summary = 'Largest city in Japan'",
    )
    .unwrap();
    assert_eq!(
        fts(&conn, "Entity", "node_name_and_summary", "Largest").len(),
        1
    );
    assert_eq!(
        conn.fts_repair_count(),
        0,
        "the open-time rebuild means the backstop never fires"
    );
}
